#!/bin/bash
# Install the ESP-IDF toolchain this repository builds with, for use WITHOUT
# Docker and WITHOUT root. The Docker path (Dockerfile) uses the official
# espressif/idf:v4.4.7 image instead and does not need this script.
#
# What it does, idempotently:
#   1. clones ESP-IDF v4.4.7 (with submodules) into $IDF_PATH;
#   2. creates a private Python venv in $IDF_VENV and installs IDF's
#      requirements.txt into it (the system python has no usable pip here);
#   3. installs the toolchains for the targets we build, plus port(able)
#      cmake and ninja, into $IDF_TOOLS_PATH;
#   4. writes build/env-noroot.sh, which exports IDF_PATH/IDF_TOOLS_PATH/PATH.
#
# After the first run, every shell that builds this repository does:
#
#     source build/env-noroot.sh
#     bash scripts/build-libs.sh
#
# Defaults follow the environment this repository is developed in; override any
# of the variables below to install elsewhere.
#
#   IDF_PATH        /home/dsh/esp-idf-v4.4.7
#   IDF_TOOLS_PATH  /home/dsh/.espressif
#   IDF_VENV        /home/dsh/idf-venv
#   IDF_TARGETS     esp32,esp32s3,esp32c3
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IDF_VERSION="${IDF_VERSION:-v4.4.7}"
IDF_PATH="${IDF_PATH:-/home/dsh/esp-idf-v4.4.7}"
IDF_TOOLS_PATH="${IDF_TOOLS_PATH:-/home/dsh/.espressif}"
IDF_VENV="${IDF_VENV:-/home/dsh/idf-venv}"
IDF_TARGETS="${IDF_TARGETS:-esp32,esp32s3,esp32c3}"
IDF_GIT_URL="${IDF_GIT_URL:-https://github.com/espressif/esp-idf.git}"

export IDF_PATH IDF_TOOLS_PATH

log() { printf '\n=== %s\n' "$*"; }

# 1. ESP-IDF ------------------------------------------------------------------
if [ ! -d "$IDF_PATH/.git" ]; then
  log "cloning ESP-IDF $IDF_VERSION into $IDF_PATH"
  mkdir -p "$(dirname "$IDF_PATH")"
  git clone -b "$IDF_VERSION" --recursive --shallow-submodules \
    "$IDF_GIT_URL" "$IDF_PATH"
else
  log "ESP-IDF already present at $IDF_PATH"
fi
# Pull in any missing submodule (no-op when the clone already has them).
git -C "$IDF_PATH" submodule update --init --recursive
# Refuse to silently build with the wrong IDF: build-libs.sh assumes 4.4.7.
have="$(git -C "$IDF_PATH" describe --tags 2>/dev/null || echo unknown)"
if [ "$have" != "$IDF_VERSION" ]; then
  echo "WARNING: $IDF_PATH is at '$have', expected '$IDF_VERSION'" >&2
fi

# 2. Python venv --------------------------------------------------------------
log "preparing Python venv $IDF_VENV"
if [ ! -x "$IDF_VENV/bin/python" ]; then
  python3 -m venv "$IDF_VENV"
fi
"$IDF_VENV/bin/python" -m pip install --quiet --upgrade pip wheel
"$IDF_VENV/bin/python" -m pip install --quiet -r "$IDF_PATH/requirements.txt"
PY="$IDF_VENV/bin/python"

# 3. Toolchains + portable cmake/ninja ---------------------------------------
log "installing IDF tools for targets: $IDF_TARGETS"
"$PY" "$IDF_PATH/tools/idf_tools.py" install --targets="$IDF_TARGETS"
# cmake/ninja are optional for idf_tools, but the build needs them; installing
# them here keeps the build independent of whatever the host provides.
"$PY" "$IDF_PATH/tools/idf_tools.py" install cmake ninja --targets="$IDF_TARGETS"

# 4. Export helper ------------------------------------------------------------
log "writing $REPO/build/env-noroot.sh"
mkdir -p "$REPO/build"
cat > "$REPO/build/env-noroot.sh" <<EOF
# Generated by scripts/setup-idf-noroot.sh -- source this before building.
export IDF_PATH="$IDF_PATH"
export IDF_TOOLS_PATH="$IDF_TOOLS_PATH"
export PATH="$IDF_VENV/bin:\$PATH"
eval "\$("$PY" "\$IDF_PATH/tools/idf_tools.py" export --format key-value)"
# IDF's component manager needs a writable cache; keep it out of \$HOME.
export IDF_COMPONENT_CACHE_PATH="\$IDF_TOOLS_PATH/idf-component-cache"
export IDF_COMPONENT_MANAGER_CACHE="\$IDF_COMPONENT_CACHE_PATH"
mkdir -p "\$IDF_COMPONENT_CACHE_PATH"
EOF

log "done"
echo "IDF:       $("$PY" "$IDF_PATH/tools/idf_tools.py" list 2>/dev/null >/dev/null && echo "$IDF_PATH ($have)")"
echo "tools:     $IDF_TOOLS_PATH"
echo "python:    $PY"
echo
echo "now run:  source $REPO/build/env-noroot.sh"
